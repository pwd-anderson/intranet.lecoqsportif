SELECT
    'https://www.lecoqsportif.com/cdn/shop/files/' 
        + LEFT(ITM.ITMREF_0, CHARINDEX('_', ITM.ITMREF_0 + '_') - 1) 
        + '_2.webp' AS PHOTO,
    ITM.ITMREF_0 AS CODE_ARTICLE,
    ITM.ITMDES1_0 AS DESCRIPTION_ARTICLE,
    ITM.ZMODELCOD_0 AS CODE_MODELE,
    CASE WHEN ITM.ZNOOSFLG_0 = 2 THEN 'Oui' ELSE 'Non' END AS NOOS,
    YIL.YCOLLECT_0 AS COLLECTION,
    CASE WHEN ISNULL(ZIC.ZDROPPED_0, 0) <> 2 THEN 'Non Droppée' ELSE 'Droppée' END AS COLLECTION_DROPPEE,
    ATX.TEXTE_0 AS MOTIF_DROPPEE,
    ITM.TCLCOD_0 AS FAMILLE,
    ITM.TSICOD_1 AS GROUPE,
    ITM.ZSTYLELIKE_0 AS CODE_GENERIQUE,
    ITM.TSICOD_0 AS GENRE,
    ZIC.ZAGEGRP_0 AS GROUPE_AGE,
    ITM.CUSREF_0 AS CODE_DOUANIER,
    ZIC.ZCRYORI_0 AS ORIGINE,
    ZIC.ZITMBPS_0 AS FOURNISSEUR,
    BPS.BPSNAM_0 AS NOM_FOURNISSEUR,
    CASE WHEN CAST(ZIC.ZDATINTRO_0 AS DATE) = '1753-01-01' THEN NULL ELSE CONVERT(varchar(10), ZIC.ZDATINTRO_0, 23) END AS DATE_INTRODUCTION,
    ZIC.ZSEGOFF_0 AS SEGMENT_OFFRE,
    ATX2.TEXTE_0 AS SOUS_CATEGORY,
    ATX3.TEXTE_0 AS SMUCustomer,
    ATX4.TEXTE_0 AS Division,
    ATX5.TEXTE_0 AS ProductLineCode,
    ZIC.ZROYALCOD_0 AS ROYALTIES,
    ZIC.ZCLASSCOD_0 AS CODE_FEDAS,
    ZIC.ZMATDES_0 AS COMPO_MAT_GLOBALE

FROM X3_LCS.ITMMASTER ITM
INNER JOIN X3_LCS.YITMCOLLECT YIL 
        ON YIL.ITMREF_0 = ITM.ITMREF_0
LEFT JOIN X3_LCS.ZITMCOL ZIC 
       ON ZIC.ITMREF_0   = LEFT(ITM.ITMREF_0, CHARINDEX('_', ITM.ITMREF_0 + '_') - 1) 
      AND ZIC.YCOLLECT_0 = YIL.YCOLLECT_0
LEFT JOIN X3_LCS.BPSUPPLIER BPS 
       ON BPS.BPSNUM_0 = ZIC.ZITMBPS_0
LEFT  JOIN X3_LCS.ATEXTRA ATX
        ON ATX.IDENT2_0  = ZIC.ZANNUCOD_0
       AND ATX.CODFIC_0  = 'ATABDIV' AND ATX.LANGUE_0  = 'FRA'
       AND ATX.ZONE_0    = 'LNGDES'  AND ATX.IDENT1_0  = '6009'

LEFT  JOIN X3_LCS.ATEXTRA ATX2
        ON ATX2.IDENT2_0  = ZIC.ZTCLCOD_0
       AND ATX2.CODFIC_0  = 'ATABDIV' AND ATX2.LANGUE_0  = 'FRA'
       AND ATX2.ZONE_0    = 'LNGDES'  AND ATX2.IDENT1_0  = '6000'

LEFT  JOIN X3_LCS.ATEXTRA ATX3
        ON ATX3.IDENT2_0  = ZIC.ZCODSMU_0
       AND ATX3.CODFIC_0  = 'ATABDIV' AND ATX3.LANGUE_0  = 'FRA'
       AND ATX3.ZONE_0    = 'LNGDES'  AND ATX3.IDENT1_0  = '6019'

LEFT  JOIN X3_LCS.ATEXTRA ATX4
        ON ATX4.IDENT2_0  = ZIC.ZDIVISION_0
       AND ATX4.CODFIC_0  = 'ATABDIV' AND ATX4.LANGUE_0  = 'FRA'
       AND ATX4.ZONE_0    = 'LNGDES'  AND ATX4.IDENT1_0  = '6006'

LEFT  JOIN X3_LCS.ATEXTRA ATX5
        ON ATX5.IDENT2_0  = ZIC.ZLINEPROD_0
       AND ATX5.CODFIC_0  = 'ATABDIV' AND ATX5.LANGUE_0  = 'FRA'
       AND ATX5.ZONE_0    = 'LNGDES'  AND ATX5.IDENT1_0  = '6001'

WHERE ITM.ITMREF_0 NOT LIKE '%[_]%'
    {{COLLECTION_WHERE}}
    {{FAMILLE_WHERE}}
    {{GENRE_WHERE}}
