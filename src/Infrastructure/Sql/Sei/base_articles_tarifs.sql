-- Base Articles/Tarifs : une ligne par article PARENT et par collection.
-- Prix achat (1PFCOL), frais d'approche (8PFFA) et tarifs de vente (T10/T11) sont d'abord ramenés à UNE valeur
-- par (modèle, collection[, code tarif]) : le plus récent (date de fin, date de début, ligne), sinon la requête
-- démultiplierait les lignes (un tarif de vente = une ligne dans SPRICLIST, des doublons existent).
WITH PrixAchat AS (
    SELECT PPL.PLICRI2_0 AS MODELE, PPL.PLICRI1_0 AS COLLECTION, PPL.PRI_0, PPL.CUR_0,
           ROW_NUMBER() OVER (
               PARTITION BY PPL.PLICRI2_0, PPL.PLICRI1_0
               ORDER BY PPL.PLIENDDAT_0 DESC, PPL.PLISTRDAT_0 DESC, PPL.PLILIN_0 DESC
           ) AS rn
    FROM X3_LCS.PPRICLIST PPL
    INNER JOIN X3_LCS.PPRICFICH PPF
            ON PPL.PLICRD_0 = PPF.PLICRD_0 AND PPL.PLI_0 = PPF.PLI_0
    WHERE PPF.PLI_0 = '1PFCOL'
),
FraisApproche AS (
    SELECT PPL.PLICRI2_0 AS MODELE, PPL.PLICRI1_0 AS COLLECTION,
           PPL.DCGVAL_0, PPL.DCGVAL_1, PPL.DCGVAL_2, PPL.DCGVAL_3,
           ROW_NUMBER() OVER (
               PARTITION BY PPL.PLICRI2_0, PPL.PLICRI1_0
               ORDER BY PPL.PLIENDDAT_0 DESC, PPL.PLISTRDAT_0 DESC, PPL.PLILIN_0 DESC
           ) AS rn
    FROM X3_LCS.PPRICLIST PPL
    INNER JOIN X3_LCS.PPRICFICH PPF
            ON PPL.PLICRD_0 = PPF.PLICRD_0 AND PPL.PLI_0 = PPF.PLI_0
    WHERE PPF.PLI_0 = '8PFFA'
),
TarifVente AS (
    SELECT SPL.PLICRI3_0 AS MODELE, SPL.PLICRI2_0 AS COLLECTION, SPL.PLICRI1_0 AS CODE_TARIF, SPL.PRI_0,
           ROW_NUMBER() OVER (
               PARTITION BY SPL.PLICRI3_0, SPL.PLICRI2_0, SPL.PLICRI1_0
               ORDER BY SPL.PLIENDDAT_0 DESC, SPL.PLISTRDAT_0 DESC, SPL.PLILIN_0 DESC
           ) AS rn
    FROM X3_LCS.SPRICLIST SPL
    WHERE SPL.PLI_0 IN ('T10', 'T11')
      AND SPL.PLICRI3_0 <> ''
      AND SPL.PLICRI1_0 IN ('CSEU', 'FOEU', 'SRPZONEURO', 'SRPZEXPORT', 'WSPEUR', 'EUROPRICE', 'INTEXPUSD', 'T1USD', 'AMZEU')
),
TarifPivot AS (
    SELECT MODELE, COLLECTION,
           MAX(CASE WHEN CODE_TARIF = 'CSEU'       THEN PRI_0 END) AS TARIF_CSEU,
           MAX(CASE WHEN CODE_TARIF = 'FOEU'       THEN PRI_0 END) AS TARIF_FOEU,
           MAX(CASE WHEN CODE_TARIF = 'SRPZONEURO' THEN PRI_0 END) AS TARIF_SRP_EUR,
           MAX(CASE WHEN CODE_TARIF = 'SRPZEXPORT' THEN PRI_0 END) AS TARIF_SRP_USD,
           MAX(CASE WHEN CODE_TARIF = 'WSPEUR'     THEN PRI_0 END) AS TARIF_WSPEUR,
           MAX(CASE WHEN CODE_TARIF = 'EUROPRICE'  THEN PRI_0 END) AS TARIF_EUROPRICE,
           MAX(CASE WHEN CODE_TARIF = 'INTEXPUSD'  THEN PRI_0 END) AS TARIF_INTEXPUSD,
           MAX(CASE WHEN CODE_TARIF = 'T1USD'      THEN PRI_0 END) AS TARIF_T1USD,
           MAX(CASE WHEN CODE_TARIF = 'AMZEU'      THEN PRI_0 END) AS TARIF_AMZEU
    FROM TarifVente
    WHERE rn = 1
    GROUP BY MODELE, COLLECTION
)
SELECT
    ITM.ITMREF_0 AS CODE_ARTICLE,
    ITM.ITMDES1_0 AS DESCRIPTION_ARTICLE,
    ITM.ZMODELCOD_0 AS CODE_MODELE,
    ZMOD.ZMODDES_0 AS DESCRIPTION_MODELE,
    CASE WHEN ITM.ZNOOSFLG_0 = 2 THEN 'Oui' ELSE 'Non' END AS NOOS,
    YIL.YCOLLECT_0 AS COLLECTION,
    CASE WHEN ISNULL(ZIC.ZDROPPED_0, 0) <> 2 THEN 'Non Droppée' ELSE 'Droppée' END AS COLLECTION_DROPPEE,
    ATX.TEXTE_0 AS MOTIF_DROPPEE,
    ITM.TCLCOD_0 AS FAMILLE,
    ITM.TSICOD_0 AS GENRE,
    ZIC.ZAGEGRP_0 AS GROUPE_AGE,
    ZIC.ZCRYORI_0 AS ORIGINE,
    ZIC.ZITMBPS_0 AS FOURNISSEUR,
    BPS.BPSNAM_0 AS NOM_FOURNISSEUR,
    CASE WHEN CAST(ZIC.ZDATINTRO_0 AS DATE) = '1753-01-01' THEN NULL ELSE CONVERT(varchar(10), ZIC.ZDATINTRO_0, 23) END AS DATE_INTRODUCTION,
    ZIC.ZSEGOFF_0 AS SEGMENT_OFFRE,
    ATX2.TEXTE_0 AS SOUS_CATEGORY,
    ATX3.TEXTE_0 AS SMUCustomer,
    ATX4.TEXTE_0 AS Division,
    ATX5.TEXTE_0 AS ProductLineCode,
    ZIC.ZROYALCOD_0 AS ROYALTIES,
    ISNULL(PA.PRI_0, 0) AS PRIX_ACHAT,
    PA.CUR_0 AS DEVISE_ACHAT,
    ISNULL(PAE.PRIX_ACHAT_EUR, 0) AS PRIX_ACHAT_EUR,
    ISNULL(FA.DCGVAL_0, 0) AS FRAIS_TRANSPORT_EUR,
    ISNULL(FA.DCGVAL_1, 0) AS TAUX_DOUANE,
    ISNULL(FA.DCGVAL_2, 0) AS TAUX_COMMISSION,
    ISNULL(FA.DCGVAL_3, 0) AS TAUX_TAXE_CUIR,
    -- Landed cost EUR : prix d'achat en USD converti en EUR (taux fixe 1,15), puis frais d'approche
    -- (transport, douane, commission, taxe cuir). 0 si pas de prix d'achat.
    ISNULL(
        (
            (PAE.PRIX_ACHAT_EUR + ISNULL(FA.DCGVAL_0, 0)) * (1 + (ISNULL(FA.DCGVAL_1, 0) / 100.0))
            + PAE.PRIX_ACHAT_EUR * (ISNULL(FA.DCGVAL_2, 0) / 100.0)
            + (PAE.PRIX_ACHAT_EUR + ISNULL(FA.DCGVAL_0, 0)) * (ISNULL(FA.DCGVAL_3, 0) / 100.0)
        ), 0
    ) AS LANDED_COST_EUR,
    ISNULL(TP.TARIF_CSEU, 0) AS TARIF_CSEU,
    ISNULL(TP.TARIF_FOEU, 0) AS TARIF_FOEU,
    ISNULL(TP.TARIF_SRP_EUR, 0) AS TARIF_SRP_EUR,
    ISNULL(TP.TARIF_SRP_USD, 0) AS TARIF_SRP_USD,
    ISNULL(TP.TARIF_WSPEUR, 0) AS TARIF_WSPEUR,
    ISNULL(TP.TARIF_EUROPRICE, 0) AS TARIF_EUROPRICE,
    ISNULL(TP.TARIF_INTEXPUSD, 0) AS TARIF_INTEXPUSD,
    ISNULL(TP.TARIF_T1USD, 0) AS TARIF_T1USD,
    ISNULL(TP.TARIF_AMZEU, 0) AS TARIF_AMZEU

FROM X3_LCS.ITMMASTER ITM
INNER JOIN X3_LCS.YITMCOLLECT YIL
        ON YIL.ITMREF_0 = ITM.ITMREF_0
INNER JOIN X3_LCS.ZMODELE ZMOD
        ON ZMOD.ZMODCOD_0 = ITM.ZMODELCOD_0
LEFT JOIN PrixAchat PA
       ON PA.MODELE = ITM.ZMODELCOD_0 AND PA.COLLECTION = YIL.YCOLLECT_0 AND PA.rn = 1
LEFT JOIN FraisApproche FA
       ON FA.MODELE = ITM.ZMODELCOD_0 AND FA.COLLECTION = YIL.YCOLLECT_0 AND FA.rn = 1
CROSS APPLY (
    SELECT CASE WHEN PA.CUR_0 = 'USD' THEN PA.PRI_0 / 1.15 ELSE PA.PRI_0 END AS PRIX_ACHAT_EUR
) PAE
LEFT JOIN TarifPivot TP
       ON TP.MODELE = ITM.ZMODELCOD_0 AND TP.COLLECTION = YIL.YCOLLECT_0
LEFT JOIN X3_LCS.ZITMCOL ZIC
       ON ZIC.ITMREF_0   = LEFT(ITM.ITMREF_0, CHARINDEX('_', ITM.ITMREF_0 + '_') - 1)
      AND ZIC.YCOLLECT_0 = YIL.YCOLLECT_0
LEFT JOIN X3_LCS.BPSUPPLIER BPS
       ON BPS.BPSNUM_0 = ZIC.ZITMBPS_0

LEFT JOIN X3_LCS.ATEXTRA ATX
       ON ATX.IDENT2_0  = ZIC.ZANNUCOD_0
      AND ATX.CODFIC_0  = 'ATABDIV' AND ATX.LANGUE_0  = 'FRA'
      AND ATX.ZONE_0    = 'LNGDES'  AND ATX.IDENT1_0  = '6009'

LEFT JOIN X3_LCS.ATEXTRA ATX2
       ON ATX2.IDENT2_0  = ZIC.ZTCLCOD_0
      AND ATX2.CODFIC_0  = 'ATABDIV' AND ATX2.LANGUE_0  = 'FRA'
      AND ATX2.ZONE_0    = 'LNGDES'  AND ATX2.IDENT1_0  = '6000'

LEFT JOIN X3_LCS.ATEXTRA ATX3
       ON ATX3.IDENT2_0  = ZIC.ZCODSMU_0
      AND ATX3.CODFIC_0  = 'ATABDIV' AND ATX3.LANGUE_0  = 'FRA'
      AND ATX3.ZONE_0    = 'LNGDES'  AND ATX3.IDENT1_0  = '6019'

LEFT JOIN X3_LCS.ATEXTRA ATX4
       ON ATX4.IDENT2_0  = ZIC.ZDIVISION_0
      AND ATX4.CODFIC_0  = 'ATABDIV' AND ATX4.LANGUE_0  = 'FRA'
      AND ATX4.ZONE_0    = 'LNGDES'  AND ATX4.IDENT1_0  = '6006'

LEFT JOIN X3_LCS.ATEXTRA ATX5
       ON ATX5.IDENT2_0  = ZIC.ZLINEPROD_0
      AND ATX5.CODFIC_0  = 'ATABDIV' AND ATX5.LANGUE_0  = 'FRA'
      AND ATX5.ZONE_0    = 'LNGDES'  AND ATX5.IDENT1_0  = '6001'

WHERE ITM.ITMREF_0 NOT LIKE '%[_]%'
